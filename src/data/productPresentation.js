export function getProductPresentation(product) {
  const translation = productTranslations[product.id] ?? {};

  return {
    ...product,
    displayTitle: translation.title ?? product.title,
    displayDescription: translation.description ?? product.description,
  };
}

export function formatUsdPrice(value) {
  return new Intl.NumberFormat('pt-BR', {
    style: 'currency',
    currency: 'USD',
  }).format(Number(value));
}

export function formatDiscount(value, options = {}) {
  const maximumFractionDigits = options.maximumFractionDigits ?? 0;
  const formattedValue = new Intl.NumberFormat('pt-BR', {
    minimumFractionDigits: options.minimumFractionDigits ?? 0,
    maximumFractionDigits,
  }).format(Number(value));

  return `${formattedValue}% de desconto`;
}